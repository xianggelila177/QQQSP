import assert from 'node:assert/strict';
import {normalizeDailyBar,historyQuery,validDate,localDateAt} from '../lib/history-contract.js';
import {aggregateHistory,periodBounds,periodStatus} from '../lib/history-aggregate.js';
const row={sessionDate:'2026-09-08',o:10,h:15,l:8,c:12,v:100,source:'fixture',currency:'USD'};
for(const date of ['2026-02-30','2025-02-29','2026-13-01','2026-01-00','2026'])assert.equal(validDate(date),false,date);
assert.equal(validDate('2024-02-29'),true);
for(const value of [null,undefined,'',NaN,Infinity,'10'])assert.equal(normalizeDailyBar({...row,o:value}),null);
assert.equal(normalizeDailyBar({...row,v:undefined}).v,null);
assert.equal(normalizeDailyBar({...row,v:0}).v,0);
assert.equal(normalizeDailyBar({...row,v:-1}),null);
assert.equal(normalizeDailyBar({...row,h:9}),null);
assert.equal(localDateAt(Date.parse('2026-01-02T01:00:00Z'),'America/New_York'),'2026-01-01');
assert.equal(localDateAt(Date.parse('2026-07-02T04:00:00Z'),'America/New_York'),'2026-07-02');
assert.equal(periodBounds('2025-01-02','weekly').periodStart,'2024-12-30');
assert.equal(periodBounds('2024-02-29','monthly').periodEndExclusive,'2024-03-01');
assert.equal(periodBounds('2025-01-02','yearly').periodStart,'2025-01-01');
assert.equal(periodBounds('2026-09-08','weekly',0).periodStart,'2026-09-06');
for(const count of [0,-1,1.5,501,'0x10','1e2',''])assert.throws(()=>historyQuery('QQQ','weekly',{count}));
assert.throws(()=>historyQuery('QQQ','weekly',{before:'2026-02-30'}));
assert.equal(historyQuery('qqq','yearly').count,39);
assert.equal(historyQuery('qqq','weekly').count,79);
assert.throws(()=>aggregateHistory([row,{...row,h:16}],'weekly'),/Conflicting/);
assert.equal(aggregateHistory([row,row],'weekly')[0].v,100);
const revision=aggregateHistory([{...row,sourceRevision:1},{...row,v:300,sourceRevision:2}],'weekly')[0];
assert.equal(revision.v,300);
assert.throws(()=>aggregateHistory([row,{...row,sessionDate:'2025-01-01',currency:'GBP'}],'yearly'),/mixed history identity/);
assert.throws(()=>aggregateHistory([{...row,sessionDate:'2027-01-01'}],'yearly',{asOf:Date.parse('2026-09-10T00:00:00Z')}),/Future/);
assert.ok(aggregateHistory([{...row,sessionDate:'1965-01-04'}],'yearly')[0].t<0);
assert.equal(aggregateHistory([row,{...row,sessionDate:'2026-09-09',v:null}],'weekly')[0].v,null);
assert.equal(aggregateHistory([row,{...row,sessionDate:'2026-09-09',v:null}],'weekly')[0].knownVolume,100);
const truncated=aggregateHistory([{...row,sessionDate:'2026-07-02'}],'yearly',{requestedFrom:'2026-07-01'})[0];
assert.equal(truncated.coverageStatus,'partial');
const unknown=aggregateHistory([{...row,sessionDate:'2025-07-02'}],'yearly',{symbol:'QQQ',zone:'America/New_York',historyAsOf:'2025-12-31'})[0];
assert.equal(unknown.coverageStatus,'unknown');assert.equal(unknown.periodState,'closed');
const bounds=periodBounds('2026-11-27','weekly');
const base={symbol:'QQQ',zone:'America/New_York'};
assert.equal(periodStatus(bounds,{...base,asOf:Date.parse('2026-11-27T17:59:00Z')}),'open');
assert.equal(periodStatus(bounds,{...base,asOf:Date.parse('2026-11-27T18:00:00Z')}),'closed');
assert.equal(periodStatus(periodBounds('2027-01-04','weekly'),{...base,asOf:Date.parse('2027-01-04T15:00:00Z')}),'unknown');
console.log('History dates, identity, revisions, volume, coverage and official early-close cases passed');
